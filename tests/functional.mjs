import { createRequire } from 'module'; const require = createRequire(import.meta.url); const { chromium } = require(process.env.PW);
const out = process.argv[2];
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 800, height: 450 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto('http://127.0.0.1:5173/?quality=low');
await p.waitForFunction(() => document.querySelector('[data-go="quiet"]') && !document.querySelector('.row-btns').hidden, null, { timeout: 180000 });
await p.click('[data-go="quiet"]');
const st = () => p.evaluate(() => { const a = window.__rainfall; return { x: +a.player.x.toFixed(2), z: +a.player.z.toFixed(2), mode: a.stroll.active, blocked: a.cb.col.blocked(a.player.x, a.player.z, 0.25), photo: a.photo.active, city: a.def.id, peds: a.engine.crowd.agents.filter((q) => q.alive).length, cars: a.engine.traffic.vehicles.length }; });
const r = {};
r.start = await st();
await p.keyboard.down('w'); await p.waitForTimeout(8000); await p.keyboard.up('w');
r.afterWalk = await st();
// walk into a wall: turn right and keep walking a long time
await p.keyboard.down('d'); await p.waitForTimeout(12000); await p.keyboard.up('d');
r.afterWallPush = await st();
await p.keyboard.press('t'); await p.waitForTimeout(500); r.strollOn = await st();
await p.waitForTimeout(10000); r.strollMoved = await st();
await p.keyboard.press('w'); await p.waitForTimeout(500); r.backToWalk = await st();
await p.keyboard.press('p'); await p.waitForTimeout(800); r.photo = await st();
await p.screenshot({ path: out + '/f-photo.png' });
await p.keyboard.press('p'); await p.waitForTimeout(500); r.photoOff = await st();
await p.keyboard.press('m'); await p.waitForTimeout(800);
r.panelTabs = await p.evaluate(() => [...document.querySelectorAll('.tab')].map((t) => t.textContent));
await p.click('#tab-weather'); await p.waitForTimeout(300);
await p.screenshot({ path: out + '/f-panel.png' });
await p.click('#tab-city'); await p.waitForTimeout(300);
await p.click('.card:nth-child(4)');
await p.waitForFunction(() => window.__rainfall.def?.id === 'miami' && !window.__rainfall.switching, null, { timeout: 180000 });
r.switched = await st();
await p.keyboard.press('Escape'); await p.keyboard.press('h'); await p.waitForTimeout(300);
r.hidden = await p.evaluate(() => document.getElementById('app').classList.contains('hidden-ui'));
r.errs = errs;
console.log(JSON.stringify(r, null, 1));
await b.close();
