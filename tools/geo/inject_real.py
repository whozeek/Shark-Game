#!/usr/bin/env python3
"""Put the real-map module (tools/geo/realmap.js) and its baked data (tools/geo/real_bridgeport.b64) into the game file.

  python3 tools/geo/inject_real.py [rush-hour-routes.html]

The game reads everything between the REALMAP:BEGIN and REALMAP:END markers. The block is created in front of the "Connecticut campaign" section on the first run and replaced afterwards.
Run tools/geo/world/bake_real.mjs first when the data changes. Standard library only."""
import os, re, sys, json
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, '..', '..'))
html_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'rush-hour-routes.html')
mod = open(os.path.join(here, 'realmap.js'), encoding='utf-8').read().strip()
b64 = open(os.path.join(here, 'real_bridgeport.b64'), encoding='utf-8').read().strip()
n = len(json.dumps(json.load(open(os.path.join(here, 'real_bridgeport.json'), encoding='utf-8')), separators=(',', ':')))
# the length the game must allocate for the inflated JSON = the byte length of the compact JSON the baker wrote
n = os.path.getsize(os.path.join(here, 'real_bridgeport.json'))
block = ('/* REALMAP:BEGIN (generated by tools/geo/inject_real.py from tools/geo/realmap.js and tools/geo/real_bridgeport.b64; edit those, not this copy) */\n'
         '/* RM_DATA: Bridgeport, Connecticut. © OpenStreetMap contributors (ODbL 1.0), via OpenFreeMap vector tiles; reduced and baked by tools/geo/world/bake_real.mjs. See DATA_SOURCES.md section 6. */\n'
         'const RM_LEN=%d, RM_B64=\'%s\';\n%s\n/* REALMAP:END */' % (n, b64, mod))
html = open(html_path, encoding='utf-8').read()
pat = re.compile(r'/\* REALMAP:BEGIN.*?/\* REALMAP:END \*/', re.S)
if pat.search(html):
    html = pat.sub(lambda m: block, html, count=1)
else:
    mark = '/* ================= Connecticut campaign: the districts of CT_DATA become ordinary LEVELS'
    if mark not in html:
        sys.exit('anchor not found')
    html = html.replace(mark, block + '\n' + mark, 1)
open(html_path, 'w', encoding='utf-8').write(html)
print('ok', html_path, 'data', len(b64), 'bytes base64, json', n)
